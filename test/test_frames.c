// Feed raw RS-485 bytes through aqualinkd's get_packet() over a pipe and check the frames it returns.
// Build from the repo root after `make ./release/aqualinkd` (objects in build/), e.g. on the Pi:
//   gcc -Wall -O3 -D AQ_PDA -D AQ_MANAGER -I./source -o test_frames test/test_frames.c \
//       build/aq_serial.o build/utils.o build/packetLogger.o build/rs_msg_utils.o build/timespec_subtract.o \
//       -lpthread -lm -lrt -lsystemd
// Exits 0 when every case passes.  Stock 3.1.0 fails the seven merged-frame cases.
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <unistd.h>
#include <stdbool.h>

#include "aq_serial.h"
#include "utils.h"
#include "packetLogger.h"

#define CONFIG_C
#include "config.h"

bool _keepRunning = true;
int _rs_fd;
bool isAqualinkDStopping() { return !_keepRunning; }

static int failures = 0;

// expect: frames separated by -1, list ended by -2. A frame of just {-3} means "expect a checksum error".
static void run(const char *name, const unsigned char *wire, int wire_len, const int *expect)
{
  int p[2];
  unsigned char buf[AQ_MAXPKTLEN + 1];
  int got[64][64], got_len[64], n = 0, len;

  if (pipe(p) != 0) { perror("pipe"); exit(2); }
  if (write(p[1], wire, wire_len) != wire_len) { perror("write"); exit(2); }
  close(p[1]);

  while ((len = get_packet(p[0], buf)) != AQSERR_READ && n < 64) {
    if (len == AQSERR_CHKSUM) { got[n][0] = -3; got_len[n++] = 1; continue; }
    if (len <= 0) continue;
    for (int i = 0; i < len; i++) got[n][i] = buf[i];
    got_len[n++] = len;
  }
  close(p[0]);

  int e = 0, ok = 1, f = 0;
  for (f = 0; expect[e] != -2; f++) {
    int l = 0;
    while (expect[e + l] != -1 && expect[e + l] != -2) l++;
    if (f >= n || got_len[f] != l) ok = 0;
    else for (int i = 0; i < l; i++) if (got[f][i] != expect[e + i]) ok = 0;
    e += l;
    if (expect[e] == -1) e++;
  }
  if (f != n) ok = 0;

  printf("%s  %s\n", ok ? "PASS" : "FAIL", name);
  if (!ok) {
    failures++;
    for (int i = 0; i < n; i++) {
      printf("      got:");
      for (int j = 0; j < got_len[i]; j++) printf(got[i][j] < 0 ? " CHKSUM" : " %02x", got[i][j]);
      printf("\n");
    }
  }
}

#define W(...) (const unsigned char[]){__VA_ARGS__}, sizeof((const unsigned char[]){__VA_ARGS__})
#define E(...) (const int[]){__VA_ARGS__, -2}

int main()
{
#ifdef AQ_MANAGER
  setLoggingPrms(LOG_WARNING, false, NULL);
#else
  setLoggingPrms(LOG_WARNING, false, NULL, NULL);
#endif

  run("normal chiller ping + reply untouched",
      W(0x10,0x02,0x70,0x0c,0x00,0x00,0x00,0x00,0x8e,0x10,0x03, 0x10,0x02,0x00,0x0d,0x40,0x00,0x00,0x5f,0x10,0x03),
      E(0x10,0x02,0x70,0x0c,0x00,0x00,0x00,0x00,0x8e,0x10,0x03, -1, 0x10,0x02,0x00,0x0d,0x40,0x00,0x00,0x5f,0x10,0x03));

  run("captured 2026-10-19 23:25:36 (no DLE ETX, probe to 0x60)",
      W(0x10,0x02,0x00,0x0d,0x40,0x00,0x00,0x5f,0x10,0x02,0x60,0x00,0x72,0x10,0x03),
      E(0x10,0x02,0x00,0x0d,0x40,0x00,0x00,0x5f,0x10,0x03, -1, 0x10,0x02,0x60,0x00,0x72,0x10,0x03));

  run("captured 2026-10-19 23:28:35 (no DLE ETX, probe to 0x43), then a normal frame",
      W(0x10,0x02,0x00,0x0d,0x40,0x00,0x00,0x5f,0x10,0x02,0x43,0x00,0x55,0x10,0x03, 0x10,0x02,0x70,0x0c,0x00,0x00,0x00,0x00,0x8e,0x10,0x03),
      E(0x10,0x02,0x00,0x0d,0x40,0x00,0x00,0x5f,0x10,0x03, -1, 0x10,0x02,0x43,0x00,0x55,0x10,0x03, -1, 0x10,0x02,0x70,0x0c,0x00,0x00,0x00,0x00,0x8e,0x10,0x03));

  run("upstream example: DLE arrived, ETX did not (0x10|0x10|0x02)",
      W(0x10,0x02,0x00,0x0d,0x40,0x00,0x00,0x5f,0x10,0x10,0x02,0x33,0x30,0x75,0x10,0x03),
      E(0x10,0x02,0x00,0x0d,0x40,0x00,0x00,0x5f,0x10,0x03, -1, 0x10,0x02,0x33,0x30,0x75,0x10,0x03));

  run("1st part checksum is 0x10 (escaped on the wire), no end",
      W(0x10,0x02,0x00,0x0d,0xf1,0x00,0x00,0x10,0x00, 0x10,0x02,0x60,0x00,0x72,0x10,0x03),
      E(0x10,0x02,0x00,0x0d,0xf1,0x00,0x00,0x10,0x10,0x03, -1, 0x10,0x02,0x60,0x00,0x72,0x10,0x03));

  run("escaped 0x10 then 0x02 in data, good checksum: one frame, no split",
      W(0x10,0x02,0x00,0x0d,0x10,0x00,0x02,0x00,0x31,0x10,0x03),
      E(0x10,0x02,0x00,0x0d,0x10,0x02,0x00,0x31,0x10,0x03));

  run("escaped 0x10 then 0x02 in data, bad checksum: still rejected",
      W(0x10,0x02,0x00,0x0d,0x10,0x00,0x02,0x00,0x99,0x10,0x03),
      E(-3));

  run("1st part corrupt, 2nd good: keep 2nd",
      W(0x10,0x02,0x00,0x0d,0x40,0x00,0x00,0x99,0x10,0x02,0x60,0x00,0x72,0x10,0x03),
      E(0x10,0x02,0x60,0x00,0x72,0x10,0x03));

  run("1st part good, 2nd corrupt: keep 1st",
      W(0x10,0x02,0x00,0x0d,0x40,0x00,0x00,0x5f,0x10,0x02,0x60,0x00,0x99,0x10,0x03),
      E(0x10,0x02,0x00,0x0d,0x40,0x00,0x00,0x5f,0x10,0x03));

  run("both parts corrupt: rejected as before",
      W(0x10,0x02,0x00,0x0d,0x40,0x00,0x00,0x99,0x10,0x02,0x60,0x00,0x99,0x10,0x03),
      E(-3));

  run("plain bad checksum, no start in the middle: rejected as before",
      W(0x10,0x02,0x00,0x0d,0x40,0x00,0x00,0x5e,0x10,0x03),
      E(-3));

  run("noise, then a good frame",
      W(0x10,0x02,0xff,0x10,0x02,0x60,0x00,0x72,0x10,0x03),
      E(0x10,0x02,0x60,0x00,0x72,0x10,0x03));

  printf("%s\n", failures ? "FAILURES" : "ALL PASS");
  return failures ? 1 : 0;
}
